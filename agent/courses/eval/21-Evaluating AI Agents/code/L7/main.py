"""L7 · Lab 3: 给 Router 和 Skills 加评估 (本地化: phoenix evals 3.x + DeepSeek judge)

课程原版走 phoenix.evals 0.x 的 llm_classify + px.Client().query_spans/log_evaluations。
evals 3.x / arize-phoenix-client 2.x 的对应关系:
- llm_classify + rails            -> ClassificationEvaluator + choices
- px.Client().query_spans(query)  -> Client().spans.get_spans_dataframe(query=...)
- px.Client().log_evaluations     -> Client().spans.log_span_annotations_dataframe

三类评估:
① Router 选工具对不对 (LLM judge)
② 生成的画图代码能不能跑 (代码评估)
③ 最终回答清晰度 + SQL 生成正确性 (LLM judge)

运行: cd L7 && ../.venv/bin/python main.py  (需要本地 phoenix serve 已启动)
"""

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pandas as pd
from tqdm import tqdm

from local_stack import EVAL_KWARGS, banner, make_eval_llm, phoenix_client, run_chart_code

from utils import PROJECT_NAME, start_main_span, tools  # noqa: E402  (副作用: 注册 tracer)

from openinference.instrumentation import suppress_tracing  # noqa: E402
from phoenix.client.types.spans import SpanQuery  # noqa: E402
from phoenix.evals import evaluate_dataframe  # noqa: E402
from phoenix.evals.evaluators import ClassificationEvaluator  # noqa: E402
from phoenix.evals.utils import to_annotation_dataframe  # noqa: E402

px_client = phoenix_client()
eval_llm = make_eval_llm()

LESSON_DIR = Path(__file__).resolve().parent

agent_questions = [
    "What was the most popular product SKU?",
    "What was the total revenue across all stores?",
    "Which store had the highest sales volume?",
    "Create a bar chart showing total sales by store",
    "What percentage of items were sold on promotion?",
    "What was the average transaction value?",
]

# ---------------------------------------------------------------- 评估模板

TOOL_CALLING_PROMPT = """
You are an evaluation assistant evaluating questions and tool calls to
determine whether the tool called would answer the question. The tool
calls have been generated by a separate agent, and chosen from the list of
tools provided below. It is your job to decide whether that agent chose
the right tool to call.

    [BEGIN DATA]
    ************
    [Question]: {question}
    ************
    [Tool Called]: {tool_call}
    [END DATA]

Your response must be single word, either "correct" or "incorrect",
and should not contain any text or characters aside from that word.
"incorrect" means that the chosen tool would not answer the question,
the tool includes information that is not presented in the question,
or that the tool signature includes parameter values that don't match
the formats specified in the tool signatures below.

"correct" means the correct tool call was chosen, the correct parameters
were extracted from the question, the tool call generated is runnable and correct,
and that no outside information not present in the question was used
in the generated question.

    [Tool Definitions]: {tool_definitions}
"""

CLARITY_LLM_JUDGE_PROMPT = """
In this task, you will be presented with a query and an answer. Your objective is to evaluate the clarity
of the answer in addressing the query. A clear response is one that is precise, coherent, and directly
addresses the query without introducing unnecessary complexity or ambiguity. An unclear response is one
that is vague, disorganized, or difficult to understand, even if it may be factually correct.

Your response should be a single word: either "clear" or "unclear," and it should not include any other
text or characters. "clear" indicates that the answer is well-structured, easy to understand, and
appropriately addresses the query. "unclear" indicates that some part of the response could be better
structured or worded.
Please carefully consider the query and answer before determining your response.

[BEGIN DATA]
Query: {query}
Answer: {response}
[END DATA]

LABEL: "clear" or "unclear"
"""

SQL_EVAL_GEN_PROMPT = """
SQL Evaluation Prompt:
-----------------------
You are tasked with determining if the SQL generated appropiately answers a given instruction
taking into account its generated query and response.

Data:
-----
- [Instruction]: {question}
  This section contains the specific task or problem that the sql query is intended to solve.

- [Reference Query]: {query_gen}
  This is the sql query submitted for evaluation. Analyze it in the context of the provided
  instruction.

Evaluation:
-----------
Your response should be a single word: either "correct" or "incorrect".
You must assume that the db exists and that columns are appropiately named.
You must take into account the response as additional information to determine the correctness.
"""


def extract_tool_call_names(output_messages) -> list:
    """从 llm.output_messages 里抽出 tool call 名字列表"""
    names = []
    try:
        for msg in output_messages or []:
            message = msg.get("message", msg) if isinstance(msg, dict) else {}
            for tc in message.get("tool_calls") or []:
                tool_call = tc.get("tool_call", tc) if isinstance(tc, dict) else {}
                fn = tool_call.get("function", {})
                if fn.get("name"):
                    names.append(fn["name"])
    except Exception:
        pass
    return names


def log_annotations(results_df: pd.DataFrame, name: str, kind: str):
    ann = to_annotation_dataframe(dataframe=results_df)
    px_client.spans.log_span_annotations_dataframe(
        dataframe=ann, annotation_name=name, annotator_kind=kind
    )
    print(f"  [已回写 {len(ann)} 条 '{name}' 注解到 Phoenix]")


def score_series(results_df: pd.DataFrame, column: str) -> pd.Series:
    """evaluate_dataframe 的 *_score 列是 Score 的 JSON 串, 抽出数值 score"""

    def _score(cell):
        if isinstance(cell, str):
            cell = json.loads(cell)
        if isinstance(cell, dict):
            return cell.get("score")
        return None

    return results_df[column].map(_score)


def main():
    run_started_at = datetime.now(timezone.utc)

    banner("①", f"跑 {len(agent_questions)} 个问题, 产出 trace (project={PROJECT_NAME})")
    for question in tqdm(agent_questions, desc="Processing questions"):
        try:
            start_main_span([{"role": "user", "content": question}])
        except Exception as e:
            print(f"Error processing question: {question}\n{e}")

    def query_spans(query):
        # 只取本次运行产生的 span, 重复跑 demo 不会把历史 span 再评一遍
        return px_client.spans.get_spans_dataframe(
            query=query, project_name=PROJECT_NAME, start_time=run_started_at, timeout=60
        )

    # ---------------------------------------------------------- Router 评估
    banner("②", "Router 评估: 选的工具对不对 (LLM-as-a-judge)")
    query = SpanQuery().where("span_kind == 'LLM'").select("input.value", "llm.output_messages")
    df = query_spans(query)
    df = df.rename(columns={"input.value": "question", "llm.output_messages": "output_messages"})
    df["tool_call"] = df["output_messages"].apply(extract_tool_call_names)
    tool_calls_df = df[df["tool_call"].map(len) > 0].copy()
    tool_calls_df["tool_call"] = tool_calls_df["tool_call"].map(", ".join)
    # 工具定义作为模板变量传入 (不能直接内嵌 JSON: 花括号会被 f-string 模板当变量解析)
    tool_calls_df["tool_definitions"] = json.dumps(tools, indent=2)
    print(f"  抓到 {len(tool_calls_df)} 个带工具调用的 Router span")

    tool_call_evaluator = ClassificationEvaluator(
        name="tool_calling",
        llm=eval_llm,
        prompt_template=TOOL_CALLING_PROMPT,
        choices={"correct": 1.0, "incorrect": 0.0},
        **EVAL_KWARGS,
    )
    with suppress_tracing():
        results = evaluate_dataframe(
            dataframe=tool_calls_df[["question", "tool_call", "tool_definitions"]],
            evaluators=[tool_call_evaluator],
        )
    scores = score_series(results, "tool_calling_score")
    print(f"  Router 正确率: {scores.mean():.2f} ({int(scores.sum())}/{len(scores)})")
    log_annotations(results, "Tool Calling Eval", "LLM")

    # ---------------------------------------------------------- 代码可运行性评估
    banner("③", "Skill 评估: 生成的画图代码能不能跑 (纯代码评估, 不用 LLM)")
    query = SpanQuery().where("name == 'generate_visualization'").select("output.value")
    code_gen_df = query_spans(query)
    code_gen_df = code_gen_df.rename(columns={"output.value": "generated_code"})
    print(f"  抓到 {len(code_gen_df)} 个 generate_visualization span")

    def code_is_runnable(output: str) -> bool:
        output = str(output).strip().replace("```python", "").replace("```", "")
        return run_chart_code(output, str(LESSON_DIR / "chart_eval_tmp.png"))

    code_gen_df["label"] = code_gen_df["generated_code"].apply(code_is_runnable).map(
        {True: "runnable", False: "not_runnable"}
    )
    code_gen_df["score"] = code_gen_df["label"].map({"runnable": 1, "not_runnable": 0})
    print(code_gen_df[["label", "score"]].to_string())
    px_client.spans.log_span_annotations_dataframe(
        dataframe=code_gen_df[["label", "score"]],
        annotation_name="Runnable Code Eval",
        annotator_kind="CODE",
    )
    print("  [已回写 Runnable Code Eval 注解]")

    # ---------------------------------------------------------- 回答清晰度评估
    banner("④", "整体评估 1: 最终回答清晰度 (LLM-as-a-judge)")
    query = SpanQuery().where("span_kind == 'AGENT'").select("input.value", "output.value")
    clarity_df = query_spans(query)
    clarity_df = clarity_df.rename(columns={"input.value": "query", "output.value": "response"})
    print(f"  抓到 {len(clarity_df)} 个 AGENT span")

    clarity_evaluator = ClassificationEvaluator(
        name="clarity",
        llm=eval_llm,
        prompt_template=CLARITY_LLM_JUDGE_PROMPT,
        choices={"clear": 1.0, "unclear": 0.0},
        **EVAL_KWARGS,
    )
    with suppress_tracing():
        results = evaluate_dataframe(
            dataframe=clarity_df[["query", "response"]], evaluators=[clarity_evaluator]
        )
    scores = score_series(results, "clarity_score")
    print(f"  清晰率: {scores.mean():.2f} ({int(scores.sum())}/{len(scores)})")
    log_annotations(results, "Response Clarity", "LLM")

    # ---------------------------------------------------------- SQL 生成评估
    banner("⑤", "Skill 评估: SQL 生成正确性 (LLM-as-a-judge)")
    query = SpanQuery().where("span_kind == 'LLM'").select("input.value", "llm.output_messages")
    sql_df = query_spans(query)
    sql_df = sql_df.rename(columns={"input.value": "question", "llm.output_messages": "query_gen"})
    sql_df = sql_df[sql_df["question"].astype(str).str.contains("Generate an SQL query", na=False)]
    sql_df["query_gen"] = sql_df["query_gen"].astype(str)
    print(f"  抓到 {len(sql_df)} 个 SQL 生成 span")

    sql_evaluator = ClassificationEvaluator(
        name="sql_gen",
        llm=eval_llm,
        prompt_template=SQL_EVAL_GEN_PROMPT,
        choices={"correct": 1.0, "incorrect": 0.0},
        **EVAL_KWARGS,
    )
    with suppress_tracing():
        results = evaluate_dataframe(
            dataframe=sql_df[["question", "query_gen"]], evaluators=[sql_evaluator]
        )
    scores = score_series(results, "sql_gen_score")
    print(f"  SQL 正确率: {scores.mean():.2f} ({int(scores.sum())}/{len(scores)})")
    log_annotations(results, "SQL Gen Eval", "LLM")

    banner("⑥", "完成")
    print(f"  到 Phoenix UI ({PROJECT_NAME} 项目) 的 span 上可看到 4 类评估注解")


if __name__ == "__main__":
    main()
